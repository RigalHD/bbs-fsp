    private static final IKey[] TOOLS = keys(UIGraffitiEditor.Tool.values(), "bbs_fsp.graffiti.tools.");

    private GraffitiKeys()
    {}

    public static IKey tool(UIGraffitiEditor.Tool tool)
    {
        return TOOLS[tool.ordinal()];
    }

    /** What the form and its tracks are called, for {@link mchorse.bbs_fsp.graffiti.GraffitiForm#labels}. */
    public static String label(String key)
    {
        return switch (key)
        {
            case "form" -> TITLE.get();
            case "pixel_art" -> PIXEL_ART.get();
            case "blur" -> BLUR.get();
            case "glow" -> GLOW.get();
            case "glow_radius" -> GLOW_RADIUS.get();
            case "light_intensity" -> LIGHT_INTENSITY.get();
            case "light_radius" -> LIGHT_RADIUS.get();
            default -> null;
        };
    }

    private static IKey[] keys(Enum<?>[] values, String prefix)
    {
        IKey[] keys = new IKey[values.length];

        for (int i = 0; i < values.length; i++)
        {
            keys[i] = L10n.lang(prefix + values[i].name().toLowerCase(Locale.ROOT));
        }

        return keys;
    }
